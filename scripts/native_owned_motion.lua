program_begin(0)
disable_auto_sync()
__COMMON__
local mailbox=(function()
__MAILBOX__
end)()
local owner_module=(function()
__OWNER__
end)()
local sdk_result=(function()
__SDK_RESULT__
end)()
local raw_packets=__PACKETS__
local origin=__ORIGIN__
local final=__FINAL__
local base=__BASE__
local base_rotation=__ROTATION__
local expected={}
for i=1,#raw_packets do expected[i]=mailbox.decode(raw_packets[i]);rt_sleep(1) end
local binding={session=string.rep('15',16),model=string.rep('a9',32),generation=1}
local function same(a,b)
    for _,key in ipairs({'q','v','a'}) do for i=1,6 do if a[key][i]~=b[key][i] then return false end end end
    return true
end
local function certified(p,tail)
    -- Finite TEST whitelist generated by the host's full model validation.
    -- Not a replacement for a live publisher's packet certification.
    local e=expected[p.sequence]
    if not e or #tail~=e.braking_ticks then return false end
    for _,key in ipairs({'sequence','session','model','generation','parent_tick','due_ms','captured_ms','braking_ticks'}) do
        if p[key]~=e[key] then return false end
    end
    return same(p.start,e.start) and same(p.next,e.next) and same(p.terminal,e.terminal)
end
local count=0;local samples=0;local max_drift=0;local previous_sample=nil;local epoch=timestamp()
local finish=false;local failure=nil;local rejection=nil
local function observe(k)
    local now=timestamp()-epoch;local p=k.actual_tcp_pose
    local drift=math.sqrt((p.x-base.x)^2+(p.y-base.y)^2+(p.z-base.z)^2)
    assert(drift==drift and drift<=.001,'owned_tcp_path')
    local sx,cx=math.sin(p.rx),math.cos(p.rx);local sy,cy=math.sin(p.ry),math.cos(p.ry)
    local sz,cz=math.sin(p.rz),math.cos(p.rz)
    local r={cz*cy,cz*sy*sx-sz*cx,cz*sy*cx+sz*sx,sz*cy,sz*sy*sx+cz*cx,sz*sy*cx-cz*sx,-sy,cy*sx,cy*cx}
    local dot=0;for i=1,9 do dot=dot+r[i]*base_rotation[i] end
    assert(math.acos(math.max(-1,math.min(1,(dot-1)/2)))<=.20,'owned_rotation_region')
    assert(not previous_sample or (now>=previous_sample and now-previous_sample<100),'owned_feedback_gap')
    previous_sample=now;max_drift=math.max(max_drift,drift);samples=samples+1
    print('OWNED_SAMPLE',now,drift,p.z,k.actual_joint_speed[1])
end
local ok,err=pcall(function()
    tool_check();assert(lebai:get_velocity_factor()==100,'owned_factor')
    local state,k=read(.3);assert(state=='IDLE','owned_requires_idle')
    for i=1,6 do assert(math.abs(k.actual_joint_pose[i]-origin[i])<=1e-6
        and math.abs(k.actual_joint_speed[i])<=1e-6,'owned_origin') end
    assert(lebai:get_signal(0)==0 and lebai:get_signal(120)==0,'owned_banks_occupied')
    epoch=timestamp()
    local clock=function() return timestamp()-epoch end
    local owner=owner_module.new(binding,expected[1].start,clock,certified,500)
    owner.offer_authority(0)
    local reader=mailbox.new(function(i,n) return lebai:get_signals(i,n) end,
        function(i) return lebai:get_signal(i) end,clock,binding,500)
    local acks={}
    local point_log={};local point_log_index=1
    local function record_point(...)
        assert(#point_log<128,'owned_log_budget')
        point_log[#point_log+1]=table.pack(...)
    end
    local function worker(fn)
        return async_task(function()
            local good,reason=pcall(fn)
            if not good then failure=failure or reason;finish=true end
        end)
    end
    local receiver=worker(function()
        while not finish and not owner.released do
            local p=reader.read_latest()
            if p then
                local accepted,reason=owner.stage(p);acks[p.sequence]=accepted
                print('OWNED_ACK',p.sequence,accepted,tostring(reason),clock())
                if not accepted then rejection=reason;owner.finish('bundle_rejected');return end
            end
            rt_sleep(1)
        end
    end)
    local publisher=worker(function()
        local index=1;local active=0;local pending=nil;local last_authority=-20
        while not finish and not owner.released do
            local now=clock()
            if now-last_authority>=20 then owner.offer_authority(now);last_authority=now end
            if pending then
                if acks[pending]==true then pending=nil;index=index+1
                elseif acks[pending]==false then return end
            elseif index<=#expected then
                local p=expected[index]
                if p.captured_ms<=now and #owner.queue<2 then
                    local offset=active*120;local words=raw_packets[index];local payload={}
                    for i=2,120 do payload[#payload+1]=words[i] end
                    lebai:set_signal(offset,0);lebai:set_signals(offset+1,payload);lebai:set_signal(offset,words[1])
                    pending=p.sequence;active=1-active
                end
            elseif owner.head_tick>=#expected then
                owner.finish('release');print('OWNED_RELEASE',clock(),owner.head_tick);return
            end
            rt_sleep(1)
        end
    end)
    local monitor=worker(function()
        while not finish do local _,f=read(.3);observe(f);rt_sleep(20) end
    end)
    local logger=worker(function()
        while not finish or point_log_index<=#point_log do
            local row=point_log[point_log_index]
            if row then print(table.unpack(row,1,row.n));point_log_index=point_log_index+1
            else rt_sleep(1) end
        end
    end)
    local motion=worker(function()
        while not finish and owner.phase~='ready' do
            assert(clock()<15000,'owned_runtime_budget')
            local segment,mode=owner.take_next()
            if segment then
                assert(count<64,'owned_point_budget');entered=true
                record_point('OWNED_ENTER',count+1,clock(),owner.head_tick,mode)
                sdk_result.call_void(function()
                    return lebai:move_pvat(segment.next.q,segment.next.v,segment.next.a,.08)
                end)
                count=count+1;record_point('OWNED_POINT',count,clock(),owner.head_tick,mode)
            else
                -- The first two points are a bounded preload. Yield while
                -- waiting for a due point, not again after an awaited send.
                rt_sleep(1)
            end
        end
        finish=true
    end)
    wait_all(receiver,publisher,monitor,logger,motion)
    assert(not failure,tostring(failure))
    local last=quiet(2500,200,.3,function(k,now) observe(k) end)
    assert(not rejection,'owned_bundle_rejected')
    assert(count==#expected+expected[#expected].braking_ticks,'owned_incomplete')
    for i=1,6 do assert(math.abs(last.actual_joint_pose[i]-final[i])<.002,'owned_endpoint') end
    lebai:set_signal(0,0);lebai:set_signal(120,0)
    print('OWNED_QUIET',clock(),max_drift,samples)
end)
if not ok and entered then abort() end
print('OWNED_DONE',ok,tostring(err),count)
program_end(0)
